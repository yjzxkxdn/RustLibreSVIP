//! Helpers for the ACE plugin: MD5 and small math routines.

use libresvip_core::core::lyric_phoneme::chinese::get_pinyin_series;

/// `math.isclose(value, other, rel_tol=0.0, abs_tol=1e-6)`.
pub fn is_close_abs(a: f64, b: f64) -> bool {
    (a - b).abs() <= 1e-6
}

/// `get_pinyin_series([text])[0] or fallback`.
pub fn first_pinyin(text: &str) -> Option<String> {
    get_pinyin_series(&[text])
        .ok()
        .and_then(|series| series.first().cloned())
}

